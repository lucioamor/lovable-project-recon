import type { ReconResult } from "@nxlv-ai/lovable-core";

export interface MetricComparison {
  metric: string;
  value: number | undefined;
  p90: number | undefined;
}

export interface RankedProject {
  projectId: string;
  name: string;
  wasteScore: number;
  estimatedCreditsSaved: number;
  confidence: number;
  effort: number;
  rankScore: number;
  findings: number;
  topAction?: string;
}

const METRICS = ["public_tables", "edge_functions", "storage_size_mb", "pg_cron_active_jobs", "db_size_mb", "last_activity_days"] as const;

export function percentile(metric: string, corpus: ReconResult[], p = 90): number | undefined {
  const values = corpus
    .map((r) => metricValue(r, metric))
    .filter((v): v is number => typeof v === "number" && Number.isFinite(v))
    .sort((a, b) => a - b);
  if (values.length === 0) return undefined;
  const idx = Math.min(values.length - 1, Math.max(0, Math.ceil((p / 100) * values.length) - 1));
  return values[idx];
}

export function compareProject(project: ReconResult, corpus: ReconResult[]): MetricComparison[] {
  return METRICS.map((metric) => ({ metric, value: metricValue(project, metric), p90: percentile(metric, corpus, 90) }));
}

export function rankPortfolio(results: ReconResult[]): RankedProject[] {
  return results
    .map((result) => {
      const estimatedCreditsSaved = estimateCreditsSaved(result);
      const confidence = confidenceMultiplier(result);
      const effort = effortDivisor(result);
      return {
        projectId: String(projectAttr(result, "projectId") ?? result.project.name),
        name: result.project.name,
        wasteScore: result.score.wasteScore,
        estimatedCreditsSaved,
        confidence,
        effort,
        rankScore: Math.round((estimatedCreditsSaved * confidence * 10) / effort) / 10,
        findings: result.findings.length,
        topAction: result.importedActions[0]?.action,
      };
    })
    .sort((a, b) => b.rankScore - a.rankScore || b.wasteScore - a.wasteScore || a.name.localeCompare(b.name));
}

export function renderPortfolioReport(results: ReconResult[], opts: { sourceMode?: string } = {}): string {
  const ranked = rankPortfolio(results);
  const L: string[] = [];
  const generated = results.find((r) => r.project.evidenceGenerated)?.project.evidenceGenerated;

  L.push("# Lovable Portfolio Recon Report");
  L.push("");
  L.push(`**Projects:** ${results.length}` + (generated ? `  ` : ""));
  if (generated) L.push(`_Evidence ${generated.slice(0, 10)}_`);
  L.push("");
  L.push("## Ranked projects");
  L.push("");
  L.push("| Rank | Project | Waste-score | Findings | Est. saved | Confidence | Effort | Rank score | Top action |");
  L.push("|--:|---|--:|--:|--:|--:|--:|--:|---|");
  ranked.forEach((p, i) => {
    L.push(
      `| ${i + 1} | ${p.name} | ${p.wasteScore} | ${p.findings} | ${p.estimatedCreditsSaved} | ${formatMultiplier(p.confidence)} | ${formatMultiplier(p.effort)} | ${formatMultiplier(p.rankScore)} | ${escapeCell(p.topAction ?? "")} |`,
    );
  });
  L.push("");

  L.push("## Policy clusters");
  L.push("");
  L.push("| Policy | Projects | Rule findings | Imported actions |");
  L.push("|---|--:|--:|--:|");
  for (const cluster of policyClusters(results)) {
    L.push(`| ${cluster.policy} | ${cluster.projects} | ${cluster.findings} | ${cluster.importedActions} |`);
  }
  L.push("");

  L.push("## Corpus percentiles");
  L.push("");
  L.push("| Metric | p90 |");
  L.push("|---|--:|");
  for (const metric of METRICS) L.push(`| ${metric} | ${formatNum(percentile(metric, results, 90))} |`);
  L.push("");

  const idle = results.filter((r) => metricValue(r, "last_activity_days") !== undefined && (metricValue(r, "last_activity_days") ?? 0) > 30);
  L.push("## Idle / baseline candidates");
  L.push("");
  if (idle.length === 0) {
    L.push("_No idle projects observed in this corpus._");
  } else {
    L.push("| Project | Idle days | Active crons | Score |");
    L.push("|---|--:|--:|--:|");
    for (const r of idle.sort((a, b) => (metricValue(b, "last_activity_days") ?? 0) - (metricValue(a, "last_activity_days") ?? 0))) {
      L.push(`| ${r.project.name} | ${formatNum(metricValue(r, "last_activity_days"))} | ${formatNum(metricValue(r, "pg_cron_active_jobs"))} | ${r.score.wasteScore} |`);
    }
  }
  L.push("");
  L.push("---");
  L.push("");
  L.push(`_Generated by \`recon scan --mode ${opts.sourceMode ?? "index"}\` over ${opts.sourceMode === "corpus" ? "ProjectEvidence corpus files" : "the structured project index"}._`);
  L.push("");
  return L.join("\n");
}

function policyClusters(results: ReconResult[]): Array<{ policy: string; projects: number; findings: number; importedActions: number }> {
  const byPolicy = new Map<string, { projects: Set<string>; findings: number; importedActions: number }>();
  for (const r of results) {
    const projectId = String(projectAttr(r, "projectId") ?? r.project.name);
    for (const f of r.findings) {
      const cluster = byPolicy.get(f.policy) ?? { projects: new Set<string>(), findings: 0, importedActions: 0 };
      cluster.projects.add(projectId);
      cluster.findings++;
      byPolicy.set(f.policy, cluster);
    }
    for (const a of r.importedActions) {
      if (!a.policy) continue;
      const cluster = byPolicy.get(a.policy) ?? { projects: new Set<string>(), findings: 0, importedActions: 0 };
      cluster.projects.add(projectId);
      cluster.importedActions++;
      byPolicy.set(a.policy, cluster);
    }
  }
  return [...byPolicy.entries()]
    .map(([policy, v]) => ({ policy, projects: v.projects.size, findings: v.findings, importedActions: v.importedActions }))
    .sort((a, b) => b.projects - a.projects || a.policy.localeCompare(b.policy));
}

function estimateCreditsSaved(result: ReconResult): number {
  const explicit = [
    ...result.importedActions.map((a) => explicitCreditSignal(a.action)),
    ...result.findings.flatMap((f) => [explicitCreditSignal(f.estCreditsSaved), ...f.remediation.map((r) => explicitCreditSignal(r.estCreditsSaved))]),
  ].filter((v): v is number => v !== undefined);
  const explicitTotal = explicit.reduce((sum, value) => sum + value, 0);
  const severityProxy = result.importedActions.reduce((sum, action) => sum + severityCredits(action.severity), 0);
  const findingProxy = result.findings.reduce((sum, finding) => sum + severityCredits(finding.severity), 0);
  const idleBonus = (metricValue(result, "last_activity_days") ?? 0) > 30 ? 15 : 0;
  return Math.max(1, Math.round(explicitTotal + severityProxy + findingProxy + idleBonus));
}

function confidenceMultiplier(result: ReconResult): number {
  const imported = result.importedActions.map((a) => statusConfidence(a.status));
  const findings = result.findings.map((f) => (f.confidence === "confirmed" ? 1 : 0.5));
  const values = [...imported, ...findings];
  if (values.length === 0) return 0.5;
  return Math.round((values.reduce((sum, value) => sum + value, 0) / values.length) * 100) / 100;
}

function effortDivisor(result: ReconResult): number {
  const values = [...result.importedActions.map((a) => effortPoints(a.effort)), ...result.findings.flatMap((f) => f.remediation.map((r) => effortFromText(r.body)))].filter((v): v is number => v !== undefined);
  if (values.length === 0) return 3;
  return Math.round((values.reduce((sum, value) => sum + value, 0) / values.length) * 10) / 10;
}

function explicitCreditSignal(value: string | undefined): number | undefined {
  if (!value) return undefined;
  const credit = /(\d+(?:\.\d+)?)\s*credits?\b/i.exec(value);
  if (credit) return Number(credit[1]);
  const invocations = /[-~]\s*(\d+(?:\.\d+)?)\s*(?:invocations?|inv|edge calls|ef)?\s*\/\s*day\b/i.exec(value);
  if (invocations) return Math.round(Number(invocations[1]) / 100);
  return undefined;
}

function severityCredits(severity: string | undefined): number {
  return { critical: 40, high: 25, medium: 12, low: 4 }[severity?.toLowerCase() ?? ""] ?? 0;
}

function statusConfidence(status: string | undefined): number {
  return status === "Confirmed" ? 1 : status === "Hypothesis" ? 0.5 : 0.75;
}

function effortPoints(effort: string | undefined): number | undefined {
  return { XS: 1, S: 2, M: 4, L: 8 }[effort ?? ""];
}

function effortFromText(value: string): number | undefined {
  if (/\bmanual\b|\breview\b/i.test(value)) return 4;
  if (/\bupdate\b|\bset\b|\bdelete\b|\bdrop\b/i.test(value)) return 2;
  return undefined;
}

function metricValue(result: ReconResult, metric: string): number | undefined {
  const obs = result.observations.find((o) => o.resourceId === "project" && o.metric === metric);
  if (typeof obs?.value === "number") return obs.value;
  const attr = projectAttr(result, metric);
  return typeof attr === "number" ? attr : undefined;
}

function projectAttr(result: ReconResult, key: string): unknown {
  return result.resources.find((r) => r.kind === "project")?.attrs[key];
}

function formatNum(value: number | undefined): string {
  return value === undefined ? "" : Number.isInteger(value) ? String(value) : value.toFixed(1);
}

function formatMultiplier(value: number): string {
  return Number.isInteger(value) ? String(value) : value.toFixed(1);
}

function escapeCell(value: string): string {
  return value.replace(/\|/g, "\\|");
}
